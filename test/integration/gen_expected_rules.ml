(** Print dune rules that compile each Stan file with stanc and diff the result
    against [<name>.<ext>]. Usage:
    [gen_expected_rules <ext> "<stanc flags>" <files...>] *)

open Std

(** [name] is the file name without a trailing [.stan], so [foo.stanfunctions]
    and [foo.stan] get different expected files *)
let print_rules ~ext ~flags file =
  let name =
    Filename.basename (String.chop_suffix_if_exists file ~suffix:".stan") in
  let output = Printf.sprintf "%s.%s.output" name ext in
  let deps =
    if String.includes ~affix:"include-paths" flags then
      "\n (deps (glob_files ../*.stan))"
    else "" in
  Printf.printf
    {|
(rule%s
 (alias runtest)
 (action
  (progn
   (with-stdout-to
    %s
    (run
     %%{project_root}/test/integration/run_bin_on_args.exe
     "%%{bin:stanc} %s"
     %%{dep:%s}))
   (diff? %s %s))))
|}
    deps output flags file
    (name ^ "." ^ ext)
    output

let () =
  match List.tl_exn (Array.to_list Sys.argv) with
  | ext :: flags :: files ->
      print_string
        "; Generated by test/integration/gen_expected_rules.exe, do not edit.\n";
      List.map ~f:(String.chop_prefix_if_exists ~prefix:"./") files
      |> List.stable_sort ~cmp:String.compare
      |> List.iter ~f:(print_rules ~ext ~flags)
  | _ -> failwith "Usage: gen_expected_rules  <ext> <flags> files..."
