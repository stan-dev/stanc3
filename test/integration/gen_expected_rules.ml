(** Print dune rules that compile each Stan file with stanc and diff the result
    against [expected_<kind>/<name>.<ext>]. The output is checked in as
    [expected_<kind>/dune.inc] and included by the directory's dune file. Dune
    needs every target named in advance, so the per-file rules are generated
    rather than written with a glob.

    Usage: [gen_expected_rules <kind> <ext> "<stanc flags>" <files...>] *)

open Std

(** [name] is the file name without a trailing [.stan], so [foo.stanfunctions]
    and [foo.stan] get different expected files *)
let print_rules ~kind ~ext ~flags file =
  let name = String.chop_suffix_if_exists file ~suffix:".stan" in
  let output = Printf.sprintf "%s.%s.output" name kind in
  Printf.printf
    {|
(rule
 (targets %s)
 (deps
  (package stanc)
  (glob_files *.stan))
 (action
  (with-stdout-to
   %%{targets}
   (run
    %%{project_root}/test/integration/run_bin_on_args.exe
    --split-output
    "%%{bin:stanc} %s"
    %%{dep:%s}))))

(rule
 (alias runtest)
 (action
  (diff expected_%s/%s.%s %s)))
|}
    output flags file kind name ext output

let () =
  match List.tl_exn (Array.to_list Sys.argv) with
  | kind :: ext :: flags :: files ->
      print_string
        "; Generated by test/integration/gen_expected_rules.exe, do not edit.\n\
         ; Run dune runtest and dune promote to update.\n";
      List.map ~f:(String.chop_prefix_if_exists ~prefix:"./") files
      |> List.stable_sort ~cmp:String.compare
      |> List.iter ~f:(print_rules ~kind ~ext ~flags)
  | _ -> failwith "Usage: gen_expected_rules <kind> <ext> <flags> files..."
