(** Print dune rules that compile each Stan file with stanc and diff the result
    against [<name>.<ext>]. Usage:
    [gen_expected_rules <ext> "<stanc flags>" <files...>] *)

open Std

(** test inputs either end in .stan or .stanfunctions. We need to make sure the
    extension is different for [foo.stan] and [foo.stanfunctions] *)
let get_filename ~kind ~ext file =
  if String.trim ext = "preserve" then
    Printf.sprintf "../expected_%s/%s" kind (Filename.basename file)
  else
    let name =
      Filename.basename (String.chop_suffix_if_exists file ~suffix:".stan")
    in
    Printf.sprintf "../expected_%s/%s.%s" kind name ext

let print_rules ~kind ~ext ~flags input_file =
  let expected_file = get_filename ~kind ~ext input_file in
  let deps =
    (* depend on sibling files when the test has #includes *)
    if String.includes ~affix:"include-paths" flags then
      "\n (deps (glob_files_rec ../*.{stan,stanfunctions,inc}))"
    else "" in
  Printf.printf
    {|
(rule%s
 (alias runtest)
 (action
  (progn
   (with-stdout-to
    %s.output
    (run
     %%{project_root}/test/integration/runner.exe
     "%%{bin:stanc} %s"
     %%{dep:%s}))
   (diff? %s %s.output))))
|}
    deps expected_file flags input_file expected_file expected_file

let list_existing ~kind () =
  let dir = "../expected_" ^ kind in
  Sys.readdir dir |> Array.to_seq
  |> Seq.map (fun s -> "../expected_" ^ kind ^ "/" ^ s)
  |> Seq.filter Sys.is_regular_file
  |> Set.Poly.of_seq

let list_expected ~kind ~ext files =
  List.map ~f:(get_filename ~ext ~kind) files |> Set.Poly.of_list

let remove_extraneous ~kind ~ext files =
  let expected = list_expected ~kind ~ext files in
  let existing = list_existing ~kind () in
  let to_remove = Set.Poly.diff existing expected in
  Set.Poly.iter
    ~f:(fun s ->
      Printf.eprintf "%s \n" s;
      Sys.remove s)
    to_remove

let () =
  match List.tl_exn (Array.to_list Sys.argv) with
  | kind :: ext :: flags :: files ->
      print_string
        "; Generated by test/integration/gen_expected_rules.exe, do not edit.\n";
      let files =
        List.map ~f:(String.chop_prefix_if_exists ~prefix:"./") files in
      List.iter ~f:(print_rules ~kind ~ext ~flags) files;
      remove_extraneous ~kind ~ext files
  | _ -> failwith "Usage: gen_expected_rules <kind> <ext> <flags> files..."
