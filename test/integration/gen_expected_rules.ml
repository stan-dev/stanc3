(** Print dune rules that compile each Stan file with stanc and diff the result
    against [<name>.<ext>]. Usage:
    [gen_expected_rules <ext> "<stanc flags>" <files...>] *)

open Std

(** test inputs either end in .stan or .stanfunctions. We need to make sure the
    extension is different for [foo.stan] and [foo.stanfunctions] *)
let get_filename ~output ~ext file =
  let file = Filename.basename file in
  let file =
    if String.trim ext = "preserve" then file
    else String.chop_suffix_if_exists file ~suffix:".stan" ^ "." ^ ext in
  output ^ "/" ^ file

let print_rules ~output ~ext ~flags input_file =
  let expected_file = get_filename ~output ~ext input_file in
  let deps =
    (* depend on sibling files when the test has #includes *)
    if String.includes ~affix:"include-paths" flags then
      "\n (deps (glob_files_rec ../*.{stan,stanfunctions,inc}))"
    else "" in
  Printf.printf
    {|
(rule%s
 (alias runtest)
 (action
  (progn
   (with-stdout-to
    %s.output
    (run
     %%{project_root}/test/integration/runner.exe
     "%%{bin:stanc} %s"
     %%{dep:%s}))
   (diff? %s %s.output))))
|}
    deps expected_file flags input_file expected_file expected_file

let list_files dir =
  Sys.readdir dir |> Array.to_seq
  |> Seq.map (Printf.sprintf "%s/%s" dir)
  |> Seq.filter Sys.is_regular_file
  |> Set.Poly.of_seq

let list_expected ~output ~ext files =
  List.map ~f:(get_filename ~ext ~output) files |> Set.Poly.of_list

let remove_extraneous ~output ~ext files =
  let expected = list_expected ~output ~ext files in
  let existing = list_files output in
  let to_remove = Set.Poly.diff existing expected in
  Set.Poly.iter
    ~f:(fun s ->
      Printf.eprintf "%s \n" s;
      Sys.remove s)
    to_remove

(** Look in the parent sandbox for the expected_ folder we should be targetting.
    This is implied by the (deps) clause for this run *)
let find_output_folder () =
  let folders =
    Sys.readdir ".." |> Array.to_seq
    |> Seq.map (( ^ ) "../")
    |> Seq.filter (fun s ->
        String.starts_with ~prefix:"../expected_" s && Sys.is_directory s)
    |> List.of_seq in
  match folders with
  | [f] -> f
  | _ ->
      failwith
        "gen_expected_rules must have (deps) containing exactly 1 'expected_' \
         folder!"

let () =
  match List.tl_exn (Array.to_list Sys.argv) with
  | ext :: flags :: files ->
      print_string
        "; Generated by test/integration/gen_expected_rules.exe, do not edit.\n";
      let files =
        List.map ~f:(String.chop_prefix_if_exists ~prefix:"./") files in
      let output = find_output_folder () in
      List.iter ~f:(print_rules ~output ~ext ~flags) files;
      remove_extraneous ~output ~ext files
  | _ -> failwith "Usage: gen_expected_rules <ext> <flags> files..."
